// ── Notes carried over from the source document ───────────────
//
// CATEGORY NOTE — why many entries have category: null
//   The source list is organised by dialect and era, which are authoritative,
//   and carries no category field. Inferring one from a short gloss proved
//   unreliable ('sod's law', 'plummy', 'gone to the dogs' resist it), so
//   category is populated only where it is genuinely clear and left null
//   otherwise. The UI therefore filters primarily on dialect / era / type /
//   flag and treats category as a secondary refinement. Filling the nulls is
//   a hand-editing job, not something to automate.
//
// IPA NOTE — why ipa is almost always null
//   1. Most of these terms are absent from js/data/pron.json (CMUdict-derived,
//      general vocabulary, not regional slang), so a derived transcription
//      would be missing or wrong.
//   2. The app's RP and Australian IPA is rule-transformed from General
//      American and already marked '≈'. Slang is exactly where rule
//      derivation is least reliable — irregular, regional, often deliberately
//      distorted. 'blackguard' is the standing example: no rule produces it.
//   3. Hand-transcription per dialect is real work and deserves a
//      phonetician's eye, not a bulk pass.
//   The field exists so those can be filled in later with no schema change.
//
// ACCURACY CAVEATS — flagged by the source author, NOT yet verified:
//   * Currency of contemporary slang ('mid', 'slaps', 'lowkey') moves fast and
//     some may already read dated — worse than using nothing. Review before
//     putting these in front of students.
//   * Australian regional variation: beer sizes (pot/middy/schooner) genuinely
//     differ by state and are simplified here. Same for 'footy', which means
//     different codes in Melbourne vs Sydney vs Perth.
//   * 'skerrick', 'she'll be apples', 'ridgy-didge', 'hooroo' are marked period
//     but may survive in older or rural speech more than credited.
//   * Period American money slang ('simoleons', 'kale', 'clams') is attested,
//     but how common each was versus merely literary is less certain.
//
// DELIBERATELY EXCLUDED
//   * Regional US (Southern, New York, Boston, Chicago), and Cockney, Estuary,
//     Scouse, Geordie, Scots — those accents are not built yet, and putting
//     their vocabulary here would teach an actor to sound like they are from
//     somewhere while claiming to be from nowhere.
//   * Māori-derived and New Zealand terms — often confused with Australian and
//     worth keeping strictly separate.
//   * SLURS. Period British, American and Australian literature all contain
//     racial slurs an actor may meet in a script. They are not listed here.
//     If comprehension of period text requires them, that belongs in a
//     separate, deliberately-designed reference with historical framing, no
//     example sentences and no practice drills — never mixed into a browsable
//     list the app might serve as an exercise.


