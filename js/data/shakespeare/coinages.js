// THE NAME IS THE CLAIM, AND IT IS DELIBERATELY NARROW. These are words whose
// earliest surviving printed use is a Shakespeare text. That is NOT the same as
// words he invented, and this file never says it is. The OED states in its own
// Preface to the Third Edition that a first citation means only that no earlier
// evidence has yet come to light; its third edition has already cut the tally
// from about 2,000 to 1,467 and is unfinished. Four other totals circulate —
// Hart's ~3,200, Crystal's ~1,700 ESTIMATE, and this source's 594 — and none of
// them counts inventions. docs/SHAKESPEARE_COINAGE_CANDIDATES.md has the
// evidence; launch_lint bans the word "invented" on this shelf.
//
// SOURCE of the word list: ElizabethanDrama.org, "Master List of Invented
// Words", compounds excluded. Their title is the claim this file declines.
//
// EVERY GLOSS WAS AUDITED. The definitions were written here, then checked
// against Alexander Schmidt's Shakespeare-Lexicon (1902), C.T. Onions' A
// Shakespeare Glossary (1911), John Foster's Word-Book (1908) and David and Ben
// Crystal's Shakespeare's Words. 503 confirmed, 82 corrected, 6 unverifiable,
// 2 found not to occur in the canon at all. `checked` carries that verdict per
// entry and is shown to the reader; it is not decoration.
//
// NO OED ACCESS was available during the audit. Glossaries are authorities on
// what a word MEANS in Shakespeare, not on who used it first, so priority
// against earlier writers is UNVERIFIED for every entry here. That is the gap
// between this shelf and any claim about coinage, and it is why the shelf is
// badged awaiting a Shakespeare scholar or verse teacher — the same footing as
// the 239-entry Dictionary that already ships.
//
// `life` is what became of the word, which is the actual lesson:
//   lives    still in ordinary English, though often in a changed sense
//   sense    the word existed; what is credited is a new MEANING
//   died     used once or twice and gone — the large majority
//   disputed the text itself is corrupt or the meaning is unknown
//   struck   the headword is spurious; kept visible, never hidden
//
// IDS ARE NEVER REUSED. SC-### is assigned once, in the source's alphabetical
// order, and a struck entry keeps its id rather than freeing it.

