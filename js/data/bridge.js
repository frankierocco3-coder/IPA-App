// The route for a self-selected pairing, approved comparisons only.
// null = nothing a learner may see — either unwritten, or written but
// still awaiting review (routeStatus tells those apart for honest copy).
export function routeFor(from, to) {
  const r = BRIDGE_ROUTES.find(x => x.from === from && x.to === to);
  if (!r) return null;
  const approved = r.comparisons.filter(c => c.reviewStatus === 'approved');
  if (!approved.length) return null;          // draft routes never reach learners
  return { ...r, comparisons: approved };
}

// Honest status for the learner-facing empty states.
//   'approved'  at least one reviewed comparison → routeFor serves it
//   'draft'     written, awaiting a qualified reviewer
//   'same'      both ends are the same accent — no route can exist
//   'missing'   not written
export function routeStatus(from, to) {
  if (from === to) return 'same';
  const r = BRIDGE_ROUTES.find(x => x.from === from && x.to === to);
  if (!r) return 'missing';
  return r.comparisons.some(c => c.reviewStatus === 'approved') ? 'approved' : 'draft';
}

// Owner review gate (#review): every route with unapproved comparisons.
// These are the NEW Build D drafts — listed separately from, and never
// counted among, the original 23-item review queue.
export const bridgeDrafts = () =>
  BRIDGE_ROUTES
    .map(r => ({ ...r, comparisons: r.comparisons.filter(c => c.reviewStatus !== 'approved') }))
    .filter(r => r.comparisons.length);

// Self-selected preference persistence (its own key; the privacy wipe
// already covers every speechcraft-* key).
const PREF_KEY = 'speechcraft-bridge';
// ── Practice gating for the LISTENING exercise ────────────────
// A comparison may become an audio question ONLY when it is approved
// AND both exact clips already exist. `hasClip(word, accent)` is
// injected so tests can prove the exclusion rule without touching the
// real audio index; the app passes audio.js's hasWordClip (which also
// honors the quarantine flags). No fallback, no substitution — a
// missing clip silently excludes the comparison from play while its
// written route data stays intact.
export function playableComparisons(route, hasClip) {
  if (!route) return [];
  return route.comparisons.filter(c =>
    c.reviewStatus === 'approved' && hasClip(c.word, route.from) && hasClip(c.word, route.to));
}

// Approved routes INTO a target accent that hold at least one playable
// comparison — the honest existence test for the Practice card. Draft
// routes can never appear here: routeFor() already drops them.
export function playableRoutesInto(target, hasClip) {
  return BRIDGE_ROUTES
    .filter(r => r.to === target && routeStatus(r.from, r.to) === 'approved')
    .map(r => routeFor(r.from, r.to))
    .filter(r => r && playableComparisons(r, hasClip).length > 0);
}

export function loadBridgePrefs() {
  try {
    const p = JSON.parse(localStorage.getItem(PREF_KEY)) ?? {};
    return { from: p.from ?? 'nam', to: p.to ?? 'rp' };
  } catch { return { from: 'nam', to: 'rp' }; }
}
export function saveBridgePrefs(from, to) {
  try { localStorage.setItem(PREF_KEY, JSON.stringify({ from, to })); } catch { /* fine */ }
}
